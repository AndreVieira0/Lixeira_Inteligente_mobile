const { test, expect } = require('@playwright/test');

test('usuário cria conta, edita perfil, mantém sessão, recupera acesso e exclui conta', async ({ page }, testInfo) => {
  const email = `tela-${Date.now()}@example.com`;
  const errors = [];
  page.on('pageerror', (error) => { errors.push(error.message); });
  await page.goto('/');
  await expect(page.getByRole('button', { name: 'Entrar', exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('login.png'), fullPage: true });
  await page.getByRole('button', { name: 'Criar uma conta', exact: true }).click();
  await page.getByRole('button', { name: 'Criar conta', exact: true }).click();
  await expect(page.getByText('Informe um e-mail válido.', { exact: true })).toBeVisible();
  await page.getByLabel('Seu nome', { exact: true }).fill('Ana Silva');
  await page.getByLabel('E-mail', { exact: true }).fill(email);
  await page.getByLabel('Senha', { exact: true }).fill('Segura123');
  await page.getByLabel('Confirmar senha', { exact: true }).fill('diferente');
  await page.getByRole('button', { name: 'Criar conta', exact: true }).click();
  await expect(page.getByText('As senhas precisam ser iguais.', { exact: true })).toBeVisible();
  await page.getByLabel('Confirmar senha', { exact: true }).fill('Segura123');
  await page.screenshot({ path: testInfo.outputPath('cadastro.png'), fullPage: true });
  await page.getByRole('button', { name: 'Criar conta', exact: true }).click();
  await expect(page.getByLabel('Nome', { exact: true })).toHaveValue('Ana Silva');
  await page.getByLabel('Nome', { exact: true }).fill('Ana Souza');
  await page.getByRole('button', { name: 'Salvar alterações', exact: true }).click();
  await expect(page.getByText('Seu perfil foi salvo.', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByLabel('Nome', { exact: true })).toHaveValue('Ana Souza');
  await page.screenshot({ path: testInfo.outputPath('perfil.png'), fullPage: true });
  await page.getByRole('button', { name: 'Sair da conta', exact: true }).click();
  await page.getByLabel('E-mail', { exact: true }).fill(email);
  await page.getByLabel('Senha', { exact: true }).fill('errada');
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page.getByText('E-mail ou senha incorretos.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Esqueci minha senha', exact: true }).click();
  await page.getByLabel('E-mail', { exact: true }).fill(email);
  await page.getByRole('button', { name: 'Enviar link', exact: true }).click();
  await expect(page.getByText(/Se houver uma conta com esse e-mail/)).toBeVisible();
  await page.getByRole('button', { name: 'Voltar para entrar', exact: true }).click();
  await page.getByLabel('E-mail', { exact: true }).fill(email);
  await page.getByLabel('Senha', { exact: true }).fill('Segura123');
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page.getByLabel('Nome', { exact: true })).toHaveValue('Ana Souza');
  await page.getByRole('button', { name: 'Excluir minha conta', exact: true }).click();
  await page.getByLabel('Senha atual', { exact: true }).fill('Segura123');
  await page.getByLabel('Digite EXCLUIR para confirmar', { exact: true }).fill('EXCLUIR');
  // Block the transaction's real HTTP request after the profile backup has been read.
  // Firestore disableNetwork only disables streams, not transaction RPCs.
  let blockedRequests = 0;
  await page.route('**/documents:batchGet**', (route) => { blockedRequests += 1; return route.abort('internetdisconnected'); });
  await page.getByRole('button', { name: 'Excluir minha conta definitivamente', exact: true }).click();
  await expect(page.getByText('O serviço está indisponível. Confira sua conexão e tente novamente.', { exact: true })).toBeVisible({ timeout: 45000 });
  expect(blockedRequests).toBeGreaterThan(0);
  await page.unroute('**/documents:batchGet**');
  await page.reload();
  await expect(page.getByLabel('Nome', { exact: true })).toHaveValue('Ana Souza');
  await page.getByRole('button', { name: 'Excluir minha conta', exact: true }).click();
  await page.getByLabel('Senha atual', { exact: true }).fill('errada');
  await page.getByLabel('Digite EXCLUIR para confirmar', { exact: true }).fill('EXCLUIR');
  await page.getByRole('button', { name: 'Excluir minha conta definitivamente', exact: true }).click();
  await expect(page.getByText('E-mail ou senha incorretos.', { exact: true })).toBeVisible();
  await page.getByLabel('Senha atual', { exact: true }).fill('Segura123');
  await page.getByRole('button', { name: 'Excluir minha conta definitivamente', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Entrar', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
