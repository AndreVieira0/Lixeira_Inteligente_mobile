const { test, expect } = require('@playwright/test');
for (const width of [360, 390, 1440]) {
  test(`lista, edição e navegação em ${width}px`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 900 });
    const errors = [];
    const backend = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => { if (/googleapis\.com|firestore|identitytoolkit|brevo|neon\.tech/.test(request.url())) backend.push(request.url()); });
    await page.goto('/');
    await page.getByRole('button', { name: 'Entrar', exact: true }).waitFor();
    await page.screenshot({ path: testInfo.outputPath('login.png'), fullPage: true });
    await page.getByRole('button', { name: 'Entrar', exact: true }).click();
    const list = page.getByRole('heading', { name: 'Minhas lixeiras', exact: true });
    await expect(list).toBeVisible();
    await expect(page.getByLabel('Buscar lixeira', { exact: true })).toHaveCount(0);
    await expect(page.getByText(/demonstração|prévia|ilustrativ/i)).toHaveCount(0);
    await page.screenshot({ path: testInfo.outputPath('lista.png'), fullPage: true });
    await page.getByRole('button', { name: 'Editar Lixeira da coordenação', exact: true }).click();
    await page.getByLabel('Nome da lixeira', { exact: true }).fill('Coordenação central');
    await page.getByLabel('Localização (opcional)', { exact: true }).fill('Bloco A');
    await page.getByRole('button', { name: 'Salvar alterações', exact: true }).click();
    await expect(list).toBeVisible();
    await expect(page.getByText('Bloco A', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Adicionar lixeira', exact: true }).click();
    await page.getByRole('button', { name: 'Salvar lixeira', exact: true }).click();
    await expect(page.getByText('Informe um nome para a lixeira.')).toBeVisible();
    await page.getByLabel('Nome da lixeira', { exact: true }).fill('Biblioteca');
    await page.getByRole('button', { name: 'Salvar lixeira', exact: true }).click();
    await expect(list).toBeVisible();
    await page.getByLabel('Buscar lixeira', { exact: true }).fill('biblioteca');
    await expect(page.getByRole('button', { name: 'Ver detalhes de Biblioteca', exact: true })).toBeVisible();
    await expect(page.getByRole('button', { name: 'Ver detalhes de Coordenação central', exact: true })).toHaveCount(0);
    await page.getByRole('button', { name: 'Limpar busca', exact: true }).click();
    await expect(page.getByLabel('Buscar lixeira', { exact: true })).toHaveValue('');
    await page.getByRole('button', { name: 'Ver detalhes de Coordenação central', exact: true }).click();
    await page.getByRole('button', { name: 'Configurar lixeira', exact: true }).click();
    await page.getByLabel('Nome da lixeira', { exact: true }).fill('Coordenação');
    await page.getByRole('button', { name: 'Salvar alterações', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Coordenação', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Ver histórico', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Histórico de ocupação' })).toBeVisible();
    await page.getByRole('button', { name: 'Voltar', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Coordenação', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Voltar', exact: true }).click();
    await expect(list).toBeVisible();
    await page.getByRole('button', { name: 'Abrir perfil', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Perfil', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Voltar', exact: true }).click();
    await expect(list).toBeVisible();
    expect(errors).toEqual([]);
    expect(backend).toEqual([]);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  });
}
